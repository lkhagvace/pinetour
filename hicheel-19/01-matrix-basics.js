// Мөр бүр = нэг массив. 🟩 сул, 🔴 захиалагдсан
const seats = [
  ["🟩", "🟩", "🔴", "🟩"], // 0-р эгнээ
  ["🔴", "🟩", "🟩", "🟩"], // 1-р эгнээ
  ["🟩", "🟩", "🟩", "🔴"], // 2-р эгнээ
];

// [мөр][багана] — эхлээд мөр, дараа нь багана
console.log(seats[0][2]); // 🔴
console.log(seats[2][1]); // 🟩
console.log(seats[1]); // ["🔴", "🟩", "🟩", "🟩"] — бүтэн мөр

// Хэмжээ
console.log(seats.length); // 3 мөр
console.log(seats[0].length); // 4 багана

// Тасалбар «Эгнээ 2, суудал 2» → индекс 0-ээс тул [1][1]
if (seats[1][1] === "🟩") {
  seats[1][1] = "🔴";
  console.log("✅ Захиаллаа");
} else {
  console.log("❌ Захиалагдсан байна");
}
console.log(seats[1]);
